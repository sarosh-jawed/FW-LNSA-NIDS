#!/usr/bin/env python3
"""Version an in-session output correction without rerunning frozen predictions.

Copies an earlier revision output tree. Corrects only NSL binary-category
sidecars: unavailable family names from training must not imply zero test
support. No seed metrics, predictions, accepted input or original tag changes.
The full old tree is retained; every byte change receives a lineage entry.
"""

from pathlib import Path
import argparse
import json
import shutil
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import pandas as pd  # noqa: E402
from src.final_validation.io import sha256, table, write_json  # noqa: E402


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--destination", required=True, type=Path)
    parser.add_argument("--secondary120", type=Path)
    parser.add_argument(
        "--preserve-complete-benchmark",
        action="store_true",
        help="Preserve an already complete80-repeat benchmark when only nonnumeric source cleanup follows",
    )
    args = parser.parse_args()
    if args.destination.exists():
        raise SystemExit("Destination exists; use a new version")
    shutil.copytree(args.source, args.destination)
    identity = args.destination / "execution_identity.json"
    if identity.exists():
        identity.rename(
            args.destination / ("source_identity_" + sha256(identity)[:16] + ".json")
        )
    if args.secondary120:
        source = args.secondary120 / "sample120k"
        target = args.destination / "sample120k"
        if (
            not (source / "manifest.json").exists()
            or json.loads((source / "manifest.json").read_text())["status"]
            != "VERIFIED_REAL_DATA"
        ):
            raise ValueError("120k study incomplete; migration refused")
        shutil.copytree(source, target)
        shutil.copyfile(
            args.secondary120 / "execution_identity.json",
            args.destination / "secondary120_execution_identity.json",
        )
    changes = []
    for name in ["category_seed_recalls.csv", "category_summary.csv"]:
        path = args.destination / "nsl_kdd_replay" / name
        if path.exists():
            before = sha256(path)
            frame = pd.read_csv(path, float_precision="round_trip")
            frame = frame[frame.category == "Attack (Unspecified)"]
            table(path, frame)
            changes.append(
                {
                    "file": str(path.relative_to(args.destination)),
                    "before_sha256": before,
                    "after_sha256": sha256(path),
                    "reason": "Only binary test category supported; unavailable family labels do not imply absent families",
                }
            )
    for path in (args.destination / "nsl_kdd_replay/units").glob("*/categories.csv"):
        before = sha256(path)
        frame = pd.read_csv(path, float_precision="round_trip")
        frame = frame[frame.category == "Attack (Unspecified)"]
        table(path, frame)
        changes.append(
            {
                "file": str(path.relative_to(args.destination)),
                "before_sha256": before,
                "after_sha256": sha256(path),
                "reason": "Binary-category sidecar only; replay metrics untouched",
            }
        )
    # Bottom-up, update manifests to the newly versioned sidecar byte hashes.
    for path in sorted(
        args.destination.rglob("manifest.json"),
        key=lambda p: len(p.parts),
        reverse=True,
    ):
        state = json.loads(path.read_text())
        if not state.get("status", "").startswith("VERIFIED_"):
            continue
        for rel in state.get("outputs", {}):
            file = path.parent / rel
            if file.exists():
                state["outputs"][rel] = sha256(file)
        write_json(path, state)
    # New report is regenerated by the final CLI, not copied as a completed gate.
    # The final controlled benchmark adds strict .01 cases to the original
    # .05 diagnostics. Preserve earlier repeats in source; rerun new protocol.
    earlier_benchmark = args.destination / "benchmark"
    if earlier_benchmark.exists():
        if args.preserve_complete_benchmark:
            state = json.loads((earlier_benchmark / "manifest.json").read_text())
            rows = pd.read_csv(earlier_benchmark / "benchmark_repeats.csv")
            if state["status"] != "VERIFIED_REAL_DATA" or len(rows) != 80:
                raise ValueError("Refusing to preserve incomplete benchmark")
        else:
            shutil.rmtree(earlier_benchmark)
    report = args.destination / "report"
    if report.exists():
        shutil.rmtree(report)
    old_lineage = args.destination / "migration_lineage.json"
    if old_lineage.exists():
        old_lineage.rename(
            args.destination
            / ("migration_lineage_prior_" + sha256(old_lineage)[:16] + ".json")
        )
    write_json(
        args.destination / "migration_lineage.json",
        {
            "source_output_root": str(args.source),
            "retained_source_tree": True,
            "changes": changes,
            "numerical_seed_results_changed": False,
            "accepted_evidence_changed": False,
            "source_change_scope": "output export inventory, equivalent DataFrame assembly for mRMR, report rendering, and binary-only NSL category universe",
            "next_step": "Run final CLI at destination to establish exact new source identity and revalidate all cached output hashes",
        },
    )
    print("Versioned output migration complete:", args.destination)


if __name__ == "__main__":
    main()
